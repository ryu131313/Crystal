using System.Text;

namespace WebRelay;

/// <summary>
/// --emit-ts: writes WebClient/src/protocol/enums.generated.ts from the compiled Shared enums, so packet ids and the
/// numeric enums the web client uses can never drift from the server by hand. Re-run after any Shared/Enums.cs change.
/// Emitted as `as const` objects (erasable TS: works with node --experimental-strip-types) plus a name lookup.
/// </summary>
internal static class TsEmitter
{
    private static readonly Type[] Enums =
    {
        typeof(ServerPacketIds), typeof(ClientPacketIds),
        typeof(MirDirection), typeof(MirClass), typeof(MirGender), typeof(ObjectType), typeof(MirAction),
        typeof(ChatType), typeof(Monster), typeof(LightSetting), typeof(Spell), typeof(PoisonType),
        typeof(DamageType), typeof(ItemType), typeof(RequiredType), typeof(EquipmentSlot), typeof(MirGridType), typeof(PanelType), typeof(SpellEffect), typeof(BuffType), typeof(SpellToggleState), typeof(Stat), typeof(DoorState),
        typeof(AttackMode), typeof(PetMode), typeof(OutputMessageType), typeof(ItemSet), typeof(BindMode), typeof(SpecialItemMode), typeof(StatFormula),
        typeof(RequiredClass), typeof(RequiredGender), typeof(ItemGrade), typeof(MarketItemType), typeof(MarketPanelType), typeof(MarketCollectionMode), typeof(AwakeType), typeof(QuestState), typeof(QuestType), typeof(QuestIcon),
        typeof(IntelligentCreatureType), typeof(IntelligentCreaturePickupMode), typeof(MountSlot), typeof(FishingSlot), typeof(HeroSpawnState), typeof(HeroBehaviour),
        typeof(AllowToggle),
        typeof(QuestCategory), typeof(QuestRepeatPolicy), typeof(QuestShareMode), typeof(QuestCreditMode), typeof(QuestFailPolicy), typeof(QuestFlags),
        typeof(QuestStepCompletion), typeof(QuestObjectiveType), typeof(QuestPartyCredit), typeof(QuestTargetKind), typeof(QuestGroupKind), typeof(QuestRotatePolicy),
        typeof(QuestEndpointRole), typeof(QuestEndpointKind), typeof(QuestRewardScope), typeof(QuestRewardKind), typeof(QuestRewardScaling),
        typeof(QuestConditionOp), typeof(QuestConditionLeaf), typeof(QuestCompare), typeof(QuestRunStatus), typeof(QuestRequestKind), typeof(QuestRefusal),
    };

    public static int Emit(string outFile)
    {
        var sb = new StringBuilder();
        sb.Append("// GENERATED by `WebRelay --emit-ts` from the compiled Shared enums (Shared/Enums.cs). Do not edit by hand.\n");
        sb.Append("// Regenerate: dotnet run --project WebRelay -- --emit-ts WebClient/src/protocol/enums.generated.ts\n\n");
        foreach (var t in Enums)
        {
            sb.Append($"export const {t.Name} = {{\n");
            var seen = new HashSet<string>();
            foreach (var name in Enum.GetNames(t))
            {
                if (!seen.Add(name)) continue;
                object value = Convert.ChangeType(Enum.Parse(t, name), Enum.GetUnderlyingType(t));
                sb.Append($"  {name}: {value},\n");
            }
            sb.Append("} as const;\n");
            sb.Append($"export type {t.Name} = (typeof {t.Name})[keyof typeof {t.Name}];\n");
            sb.Append($"export const {t.Name}Name: Readonly<Record<number, string>> = Object.fromEntries(Object.entries({t.Name}).map(([k, v]) => [v, k]));\n\n");
        }
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(outFile))!);
        File.WriteAllText(outFile, sb.ToString().Replace("\r\n", "\n"), new UTF8Encoding(false));
        Console.WriteLine($"Wrote {outFile} ({Enums.Length} enums)");
        return 0;
    }
}
