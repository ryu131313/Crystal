using System.Globalization;
using System.Text.Json;
using Server.WebAdmin.GameData;

namespace Server.WebAdmin.LiveDb
{
    /// <summary>One table's part of a batch: edited / new rows (grid wire shape, only changed cells + Index + __rev) and deletes.</summary>
    internal sealed class LiveDbTableOps
    {
        public string Endpoint;
        public List<JsonElement> Rows = new List<JsonElement>();
        public List<int> Deletes = new List<int>();

        /// <summary>
        /// Optional per-delete revision guard (index → the <c>__rev</c> the row must still have): a row whose current rev differs is
        /// a conflict and rejects the whole batch. Undo uses it to delete a row it inserted only while nothing changed it since.
        /// </summary>
        public Dictionary<int, string> DeleteRevs = new Dictionary<int, string>();

        /// <summary>Skip the __rev check (imports only; never sent by the grid).</summary>
        public bool NoRev;
    }

    /// <summary>
    /// A LiveDb batch: every change of one admin action, applied all-or-nothing. The client generates <see cref="Id"/> and reuses it
    /// on a retry, so a repeated request returns the first outcome instead of applying twice.
    /// </summary>
    internal sealed class LiveDbBatchRequest
    {
        public const int MaxIdLength = 64;

        public string Id;
        public string Reason;

        /// <summary>Also write the editor copy's other unsaved (non-LiveDb) changes; otherwise those make the batch answer 409.</summary>
        public bool FlushUnsaved;

        public bool DryRun;
        public string Admin;
        public string Ip;

        /// <summary>"livedb" (the batch route), "put" (PUT /api/admin/db/{endpoint}?live=1) or "undo" (POST /api/admin/livedb/undo/{id}).</summary>
        public string Source = "livedb";

        /// <summary>Undo: the id of the batch this one reverses (journaled, shown in the history).</summary>
        public string InverseOf;

        /// <summary>Extra sentences for the outcome message (undo: rows that stay in the running world until a restart, ...).</summary>
        public List<string> Notes = new List<string>();

        public List<LiveDbTableOps> Tables = new List<LiveDbTableOps>();

        public int OpCount
        {
            get
            {
                var n = 0;
                foreach (var t in Tables) n += t.Rows.Count + t.Deletes.Count;
                return n;
            }
        }

        public static bool IsValidId(string id)
        {
            if (string.IsNullOrEmpty(id) || id.Length > MaxIdLength) return false;
            foreach (var ch in id)
                if (!(char.IsAsciiLetterOrDigit(ch) || ch == '-' || ch == '_' || ch == '.' || ch == ':')) return false;
            return true;
        }

        /// <summary>
        /// Parses <c>{id, reason?, flushUnsaved?, dryRun?, tables:[{endpoint, rows:[...], deletes:[...], noRev?}]}</c> (HTTP thread).
        /// Throws <see cref="WebAdminException"/> 400 on a malformed body.
        /// </summary>
        public static LiveDbBatchRequest Parse(JsonElement body)
        {
            if (body.ValueKind != JsonValueKind.Object) throw new WebAdminException(400, "Expected a JSON object body {id, tables:[...]}");

            var req = new LiveDbBatchRequest
            {
                Id = (body.GetString("id") ?? string.Empty).Trim(),
                Reason = body.GetString("reason"),
                FlushUnsaved = body.GetBool("flushUnsaved"),
                DryRun = body.GetBool("dryRun"),
            };

            if (!IsValidId(req.Id))
                throw new WebAdminException(400, "'id' is required: 1-" + MaxIdLength + " characters (letters, digits, - _ . :), generated by the client and reused on retry");

            if (!body.TryGetPropertyIgnoreCase("tables", out var tables) || tables.ValueKind != JsonValueKind.Array)
                throw new WebAdminException(400, "Missing 'tables' array");

            foreach (var t in tables.EnumerateArray())
            {
                if (t.ValueKind != JsonValueKind.Object) throw new WebAdminException(400, "'tables' must contain objects {endpoint, rows, deletes}");
                var ops = new LiveDbTableOps
                {
                    Endpoint = (t.GetString("endpoint") ?? string.Empty).Trim(),
                    NoRev = t.GetBool("noRev"),
                };
                if (ops.Endpoint.Length == 0) throw new WebAdminException(400, "Every table needs an 'endpoint'");

                if (t.TryGetPropertyIgnoreCase("rows", out var rows))
                {
                    if (rows.ValueKind != JsonValueKind.Array) throw new WebAdminException(400, "'rows' must be an array");
                    foreach (var r in rows.EnumerateArray()) ops.Rows.Add(r.Clone());
                }

                if (t.TryGetPropertyIgnoreCase("deletes", out var deletes))
                {
                    if (deletes.ValueKind != JsonValueKind.Array) throw new WebAdminException(400, "'deletes' must be an array of indexes");
                    foreach (var d in deletes.EnumerateArray())
                    {
                        if (!GameDataCodec.TryGetInteger(d, out var n, out _) || n < int.MinValue || n > int.MaxValue)
                            throw new WebAdminException(400, "'deletes' must contain whole numbers");
                        ops.Deletes.Add((int)n);
                    }
                }

                if (t.TryGetPropertyIgnoreCase("deleteRevs", out var deleteRevs) && deleteRevs.ValueKind != JsonValueKind.Null)
                {
                    if (deleteRevs.ValueKind != JsonValueKind.Object) throw new WebAdminException(400, "'deleteRevs' must be an object {\"index\": \"__rev\"}");
                    foreach (var p in deleteRevs.EnumerateObject())
                    {
                        if (!int.TryParse(p.Name, NumberStyles.Integer, CultureInfo.InvariantCulture, out var index) || p.Value.ValueKind != JsonValueKind.String)
                            throw new WebAdminException(400, "'deleteRevs' maps a row index to its __rev string");
                        ops.DeleteRevs[index] = p.Value.GetString();
                    }
                }

                req.Tables.Add(ops);
            }

            if (req.Tables.Count == 0) throw new WebAdminException(400, "'tables' is empty");
            return req;
        }
    }

    /// <summary>One field change with what LiveDb does with it.</summary>
    internal sealed class LiveDbFieldOutcome
    {
        public string Field { get; set; }
        public object Before { get; set; }
        public object After { get; set; }

        /// <summary>"ReadThrough" / "Hooked" / "RestartOnly" (the effective class in this build).</summary>
        public string LiveClass { get; set; }

        public string LiveTiming { get; set; }

        /// <summary>The value reached the running world (false for restart-only fields, a stopped world or a rolled-back live step).</summary>
        public bool Live { get; set; }

        /// <summary>Why it did not reach the running world (null when it did).</summary>
        public string Reason { get; set; }
    }

    /// <summary>One row of the outcome.</summary>
    internal sealed class LiveDbRowOutcome
    {
        public string Endpoint { get; set; }

        /// <summary>The Index the client sent (≤ 0 for a new row).</summary>
        public int Index { get; set; }

        /// <summary>The row's Index after the write (allocated for inserts; 0 for a dry-run insert).</summary>
        public int NewIndex { get; set; }

        /// <summary>"update", "insert" or "delete".</summary>
        public string Kind { get; set; }

        public string Name { get; set; }

        public string RevBefore { get; set; }
        public string RevAfter { get; set; }

        /// <summary>For inserts / deletes: whether the row itself reached the running world.</summary>
        public bool? RowLive { get; set; }

        public string RowReason { get; set; }

        public List<LiveDbFieldOutcome> Changes { get; set; } = new List<LiveDbFieldOutcome>();

        /// <summary>Wire images for the journal / undo (all columns for inserts and deletes).</summary>
        internal Dictionary<string, object> BeforeImage;

        internal Dictionary<string, object> AfterImage;
    }

    /// <summary>The live step's outcome.</summary>
    internal sealed class LiveDbLiveOutcome
    {
        /// <summary>
        /// "applied" (every live field reached Main), "partial" (some fields or added / deleted rows are restart-only or refused),
        /// "none" (nothing live in this batch), "world-stopped" (saved only), "rolled-back" (a hook failed; Main restored, the save
        /// kept), "timeout" (the game thread did not pick it up; saved only), "dry-run".
        /// </summary>
        public string Outcome { get; set; } = "none";

        public int AppliedFields { get; set; }
        public int RestartFields { get; set; }
        public int MonstersQueued { get; set; }
        public int InsertedLive { get; set; }

        /// <summary>Deleted rows removed from the running world (Batch C: respawns, safe zones, movements, mine zones, game shop).</summary>
        public int DeletedLive { get; set; }

        /// <summary>Rows / fields the running world refused (conquest at war, wrong position, invalid NPC cell, quest file refused, ...).</summary>
        public int RefusedLive { get; set; }
        public int DropsReloaded { get; set; }
        public int MagicSynced { get; set; }

        /// <summary>Online players / spawned heroes whose stats were recalculated after an item change.</summary>
        public int ItemHoldersRefreshed { get; set; }

        /// <summary>Client push (S.GameDataChanged): connections, packets and rows queued.</summary>
        public int PushConnections { get; set; }

        public int PushPackets { get; set; }
        public int PushRows { get; set; }

        /// <summary>The batch changed more client-visible rows than [LiveDb] MaxPushRows: nothing was pushed (items saved only).</summary>
        public bool PushSkipped { get; set; }

        /// <summary>The push threw (logged); the world change stays applied.</summary>
        public bool PushFailed { get; set; }

        public string Message { get; set; }
    }

    /// <summary>The whole outcome of a batch (also the journal record and the LRU entry for a repeated id).</summary>
    internal sealed class LiveDbBatchResult
    {
        public string Id { get; set; }

        /// <summary>"applied", "dry-run" or "rejected".</summary>
        public string Status { get; set; }

        /// <summary>True when this answer is the stored outcome of an earlier request with the same id.</summary>
        public bool Duplicate { get; set; }

        public bool Saved { get; set; }
        public string BackupFile { get; set; }
        public DateTime Utc { get; set; }
        public string Admin { get; set; }
        public string Reason { get; set; }
        public string Source { get; set; }

        /// <summary>Undo batches: the id of the batch this one reverses; null otherwise.</summary>
        public string InverseOf { get; set; }

        /// <summary>Extra notes of the request (undo: rows the running world keeps until a restart, ...).</summary>
        public List<string> Notes { get; set; } = new List<string>();

        public string World { get; set; }

        public int Applied { get; set; }
        public int Deleted { get; set; }

        public List<LiveDbRowOutcome> Rows { get; set; } = new List<LiveDbRowOutcome>();
        public List<object> Conflicts { get; set; } = new List<object>();
        public List<object> Validation { get; set; } = new List<object>();
        public List<string> IgnoredFields { get; set; } = new List<string>();
        public List<object> Renames { get; set; } = new List<object>();

        /// <summary>"endpoint.Field" of every changed field that only takes effect after a restart.</summary>
        public List<string> RestartFields { get; set; } = new List<string>();

        public LiveDbLiveOutcome Live { get; set; } = new LiveDbLiveOutcome();

        /// <summary>A pending-reboot entry was added.</summary>
        public bool PendingReboot { get; set; }

        /// <summary>Other unsaved editor-copy changes written by this batch (flushUnsaved).</summary>
        public List<string> FlushedAreas { get; set; } = new List<string>();

        /// <summary>Unsaved non-LiveDb changes in the editor copy (dry run: the apply needs flushUnsaved when &gt; 0).</summary>
        public int UnsavedChanges { get; set; }

        public int EditorFormsOpen { get; set; }

        public Dictionary<string, long> TimingsMs { get; set; } = new Dictionary<string, long>(StringComparer.Ordinal);

        public string Message { get; set; }

        /// <summary>HTTP status for the reply (200, 409 conflicts, 422 validation).</summary>
        internal int HttpStatus = 200;

        internal LiveDbBatchResult ShallowCopy() => (LiveDbBatchResult)MemberwiseClone();

        public string Describe()
        {
            return Id + " (" + Rows.Count.ToString(CultureInfo.InvariantCulture) + " row(s), " + Status + ")";
        }
    }
}
